"""
RUNNER PARITY - FIXTURE BUILDER (RUNNER_PORT_SPEC_v1 0.4 step 1).

Builds the fixture files that scripts/runner_parity.py runs against. Each
fixture pins one real session date: the 5-minute bar arrays for a universe of
tickers, plus the gate inputs (prev close, prev volume, float, earnings), plus
the `expected` block generated by running DTO's real JavaScript over those
exact bars.

Bars come from Alpaca on the same feed the Phase 1 scan will use, so the
fixture exercises the real bar shape rather than a synthesized stand-in. It
does NOT go through agent.providers.Alpaca.multi_bars, which drops every
symbol past the first response page - see fetch_bars_paged below.

Usage:
  .venv\\Scripts\\python scripts/runner_parity_fixtures.py 2026-09-11 2026-09-10 ...
  .venv\\Scripts\\python scripts/runner_parity_fixtures.py --last 5

Options:
  --last N          the N most recent market days ending yesterday
  --universe N      cap the per-fixture ticker count (default 120)
  --cutoff HH:MM    truncate bars at this ET time, simulating a scan that ran
                    then (default 11:30, the hour DTO's scanner fires)
  --no-golden       skip the Node generator pass (fixture stays unscored)
  --dto-root PATH   DTO checkout (default $DTO_ROOT or Desktop/Trading)

A fixture is only as good as its universe. This builder uses movers +
most-actives + a fixed leveraged-ETF probe set, so every fixture contains
tickers that exercise the price gate, the RVOL gate, the exclusion gate, and
the condition check - a fixture where every ticker rejects for one reason
proves nothing.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import date, datetime, time as dtime, timedelta

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agent.config import load_config  # noqa: E402
from agent.providers import Alpaca, is_common_stock_symbol  # noqa: E402
from agent.util import ET, is_market_day, prev_market_day  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE_DIR = os.path.join(REPO, "tests", "fixtures", "runner_parity")

# Deliberate probes so no fixture is one-sided: leveraged/inverse names that
# must hit the exclusion gate, and mega-caps that must hit the price ceiling.
PROBE_EXCLUDED = ["SOXL", "SQQQ", "TQQQ", "UVXY", "LABU"]
PROBE_PRICEY = ["NVDA", "AAPL", "MSFT", "META", "TSLA"]


def build_universe(alp: Alpaca, cap: int) -> list[str]:
    syms: list[str] = []
    try:
        movers = alp.movers(top=50)
        for side in ("gainers", "losers"):
            for row in movers.get(side, []) or []:
                if row.get("symbol"):
                    syms.append(row["symbol"].upper())
    except Exception as e:
        print(f"  warn: movers fetch failed: {e}")
    try:
        for row in alp.most_actives(top=50).get("most_actives", []) or []:
            if row.get("symbol"):
                syms.append(row["symbol"].upper())
    except Exception as e:
        print(f"  warn: most-actives fetch failed: {e}")

    syms = [s for s in syms if is_common_stock_symbol(s)]
    ordered = list(dict.fromkeys(syms + PROBE_EXCLUDED + PROBE_PRICEY))
    return ordered[:cap]


def fetch_bars_paged(alp: Alpaca, symbols: list[str], timeframe: str,
                     start: datetime, end: datetime) -> dict[str, list[dict]]:
    """Multi-symbol bar fetch that FOLLOWS `next_page_token`.

    agent.providers.Alpaca.multi_bars does not. It issues one request per
    100-symbol chunk and returns whatever the first page holds, so when the
    response spans pages every symbol after the page boundary comes back with
    no bars at all - and because Alpaca orders the payload alphabetically, the
    loss is a contiguous alphabetical tail that looks exactly like "those
    tickers had no data."

    Measured on 2026-09-11, 95 symbols, 5Min, 09:30-15:00 ET: 40 symbols and
    2289 bars returned, `next_page_token` set, 55 symbols silently empty.

    That is a defect in shipped code (it also affects the ADV20 and premarket
    enrichment callers), not something this port introduced, so it is reported
    rather than patched from inside Phase 0 - RUNNER_PORT_SPEC R-3 keeps this
    lane additive and off the morning loop's path. This local helper exists so
    parity FIXTURES are built on complete bar arrays; Phase 1 1.3 cannot ship
    until the provider itself paginates.
    """
    out: dict[str, list[dict]] = {}
    for i in range(0, len(symbols), 100):
        batch = symbols[i:i + 100]
        token = None
        while True:
            params = {
                "symbols": ",".join(batch), "timeframe": timeframe,
                "start": start.isoformat(), "end": end.isoformat(),
                "limit": 10000, "adjustment": "raw", "feed": alp.feed,
            }
            if token:
                params["page_token"] = token
            data = alp._get("/v2/stocks/bars", params)
            for sym, bars in (data.get("bars") or {}).items():
                rows = out.setdefault(sym, [])
                for b in bars or []:
                    ts = datetime.fromisoformat(b["t"].replace("Z", "+00:00")).astimezone(ET)
                    rows.append({"t": ts, "o": b["o"], "h": b["h"],
                                 "l": b["l"], "c": b["c"], "v": b["v"]})
            token = data.get("next_page_token")
            if not token:
                break
    # Alpaca pages in time order within a symbol, so appending across pages
    # preserves chronology; sort anyway so the fixture never depends on it.
    for rows in out.values():
        rows.sort(key=lambda r: r["t"])
    return out


def build_fixture(alp: Alpaca, d: date, cap: int, cutoff: dtime) -> dict:
    print(f"[{d}] building universe...")
    universe = build_universe(alp, cap)
    print(f"[{d}] universe: {len(universe)} tickers")

    start = datetime.combine(d, dtime(9, 30), tzinfo=ET)
    end = datetime.combine(d, cutoff, tzinfo=ET)
    print(f"[{d}] fetching 5Min bars {start:%H:%M} -> {end:%H:%M} ET...")
    bars = fetch_bars_paged(alp, universe, "5Min", start, end)

    prev_day = prev_market_day(d)
    print(f"[{d}] fetching prev-session daily bars ({prev_day})...")
    daily = alp.multi_daily_bars(universe, prev_day, d)

    tickers: dict[str, dict] = {}
    for sym in universe:
        rows = bars.get(sym) or []
        prev = (daily.get(sym) or [])
        prev_row = prev[0] if prev else None
        tickers[sym] = {
            "bars": [
                {"t": b["t"].isoformat(), "o": b["o"], "h": b["h"],
                 "l": b["l"], "c": b["c"], "v": b["v"]}
                for b in rows
            ],
            "prev_close": prev_row["close"] if prev_row else None,
            "prev_volume": prev_row["volume"] if prev_row else None,
            # Float and earnings are left null on purpose. The JS passes a
            # null float/earnings silently, so a null here exercises exactly
            # the fail-open path the port must reproduce in "dto" mode and
            # must reject in "reject" mode (spec R-4). Populate them by hand
            # in a fixture if you want to pin the bounded-gate branches.
            "float_m": None,
            "earnings_days_away": None,
        }

    with_bars = sum(1 for t in tickers.values() if t["bars"])
    print(f"[{d}] bars returned for {with_bars}/{len(universe)} tickers")

    return {
        "session_date": d.isoformat(),
        "cutoff_et": cutoff.strftime("%H:%M"),
        "min_vwap_pct": 0.5,
        "source": f"alpaca 5Min feed={alp.feed}",
        "built_at": datetime.now(ET).isoformat(),
        "tickers": tickers,
    }


def run_golden(path: str, dto_root: str | None) -> bool:
    cmd = ["node", os.path.join(REPO, "scripts", "runner_parity_golden.mjs"), path]
    if dto_root:
        cmd += ["--dto-root", dto_root]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    except FileNotFoundError:
        print("  ERROR: `node` not found on PATH - cannot generate golden vectors.")
        return False
    sys.stdout.write(r.stdout)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        return False
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dates", nargs="*", help="session dates as YYYY-MM-DD")
    ap.add_argument("--last", type=int, default=0, help="use the N most recent market days")
    ap.add_argument("--universe", type=int, default=120)
    ap.add_argument("--cutoff", default="11:30")
    ap.add_argument("--no-golden", action="store_true")
    ap.add_argument("--dto-root", default=os.getenv("DTO_ROOT"))
    args = ap.parse_args()

    hh, mm = (int(x) for x in args.cutoff.split(":"))
    cutoff = dtime(hh, mm)

    dates: list[date] = [date.fromisoformat(s) for s in args.dates]
    if args.last:
        d = prev_market_day(datetime.now(ET).date())
        while len(dates) < args.last:
            if is_market_day(d):
                dates.append(d)
            d -= timedelta(days=1)
    if not dates:
        ap.error("give at least one date, or --last N")

    cfg = load_config()
    if not (cfg.alpaca_key_id and cfg.alpaca_secret_key):
        print("FAIL  Alpaca credentials not configured - cannot fetch real bars.")
        return 1
    alp = Alpaca(cfg)
    os.makedirs(FIXTURE_DIR, exist_ok=True)

    ok = True
    for d in sorted(set(dates)):
        if not is_market_day(d):
            print(f"[{d}] not a market day - skipping")
            continue
        fixture = build_fixture(alp, d, args.universe, cutoff)
        tag = cutoff.strftime("%H%M")
        path = os.path.join(FIXTURE_DIR, f"{d.isoformat()}_{tag}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(fixture, fh, indent=2)
            fh.write("\n")
        print(f"[{d}] wrote {os.path.relpath(path, REPO)}")
        if not args.no_golden:
            if not run_golden(path, args.dto_root):
                ok = False
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
