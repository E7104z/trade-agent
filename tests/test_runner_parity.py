# ------------------------------------------------------- trend consistency

def test_trend_consistency_counts_green_bars():
    bars = [_bar(10.5, o=10.0), _bar(9.5, o=10.0), _bar(10.0, o=10.0)]  # green, red, green(=)
    assert ri.trend_consistency(bars) == 66.7  # 2 of 3 green, toFixed(1)
    assert ri.trend_consistency([]) is None


def test_trend_consistency_uses_js_tofixed_rounding():
    """Regression: the parity harness caught this on its first randomized run.

    13 green of 16 is exactly 81.25. JS `toFixed(1)` rounds half away from
    zero -> 81.3; Python's round() rounds half to even -> 81.2. The value
    feeds a hard gate at 45.0 and a research bucket boundary, so a tie must
    land the same way it lands in the source.
    """
    bars = [_bar(10.5, o=10.0)] * 13 + [_bar(9.5, o=10.0)] * 3
    assert ri.trend_consistency(bars) == 81.3
    assert round(81.25, 1) == 81.2  # the trap this avoids


@pytest.mark.parametrize("x, digits, expected", [
    (81.25, 1, 81.3), (0.5, 0, 1.0), (2.675, 2, 2.67),  # 2.675 is really 2.67499...
    (-1.25, 1, -1.3), (1.005, 2, 1.0),                   # 1.005 is really 1.00499...
])
def test_js_to_fixed(x, digits, expected):
    assert ri.js_to_fixed(x, digits) == pytest.approx(expected)


