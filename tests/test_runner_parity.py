def test_vwap_typical_price_basis():
    """sum(tp*v)/sum(v) with tp = (h+l+c)/3, worked out by hand."""
    bars = [
        {"t": None, "o": 9, "h": 11, "l": 9,  "c": 10, "v": 100},  # tp = 10
        {"t": None, "o": 10, "h": 14, "l": 10, "c": 12, "v": 300},  # tp = 12
    ]
    # (10*100 + 12*300) / 400 = (1000 + 3600) / 400 = 11.5
    assert ri.vwap(bars) == pytest.approx(11.5)


