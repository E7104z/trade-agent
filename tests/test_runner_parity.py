def _gate_kwargs(**over):
    base = dict(prev_volume=2_000_000, prev_close=9.0, float_m=50.0,
                earnings_days_away=30)
    base.update(over)
    return base


def test_evaluate_ticker_passes_a_clean_runner():
    res = rs.evaluate_ticker("ABCD", _accel(24), **_gate_kwargs())
    assert res["passes"] is True, res["reason"]
    assert res["counter"] is None
    assert res["rvol"] is not None


