def test_excluded_tickers_no_duplicates_in_source_literal():
    """A frozenset silently absorbs a duplicated literal, which would make the
    count assertion above pass for the wrong reason."""
    import re
    src = open(rs.__file__, encoding="utf-8").read()
    block = src.split("EXCLUDED_TICKERS: frozenset[str] = frozenset([")[1].split("])")[0]
    literals = re.findall(r'"([A-Z]+)"', block)
    assert len(literals) == len(set(literals)), (
        f"duplicate literals: {sorted({t for t in literals if literals.count(t) > 1})}"
    )
    assert len(literals) == 117


def test_excluded_tickers_match_dto_source():
    """Compare against the live js/constants.js Set when the DTO repo is here."""
    dto_root = os.getenv("DTO_ROOT", r"C:/Users/Quantum Lab/Desktop/Trading")
    constants = os.path.join(dto_root, "js", "constants.js")
    if not os.path.exists(constants):
        pytest.skip(f"DTO checkout not found at {dto_root}")
    script = (
        "import('file:///' + process.argv[1].replace(/\\\\/g, '/'))"
        ".then(m => console.log(JSON.stringify([...m.EXCLUDED_TICKERS])))"
    )
    try:
        out = subprocess.run(["node", "-e", script, constants],
                             capture_output=True, text=True, timeout=60)
    except FileNotFoundError:
        pytest.skip("node not on PATH")
    if out.returncode != 0:
        pytest.skip(f"could not load constants.js: {out.stderr[:200]}")
    js_set = set(json.loads(out.stdout))
    assert js_set == set(rs.EXCLUDED_TICKERS), (
        f"only in JS: {sorted(js_set - set(rs.EXCLUDED_TICKERS))}; "
        f"only in Python: {sorted(set(rs.EXCLUDED_TICKERS) - js_set)}"
    )


