"""
Phase 0 parity tests for the DTO Runner port (specs/RUNNER_PORT_SPEC_v1.md 0.6).

Two layers:

  1. Hand-computed unit tests over agent/runner_indicators.py and
     agent/runner_scan.py - every expected value is worked out in the test
     itself, matching the tests/test_indicators.py convention.

  2. The fixture parity gate: for each fixture in tests/fixtures/runner_parity/,
     the Python scan must reproduce DTO's real JavaScript exactly - same
     passing ticker set, same numerics within tolerance, same rejection
     counters. The `expected` blocks are generated by
     scripts/runner_parity_golden.mjs running the actual DTO modules.

The fixture tests skip (rather than fail) when no fixtures are present, so a
fresh checkout without the DTO repo still runs the unit layer. Phase 0 sign-off
requires the fixtures - `python scripts/runner_parity.py` exits non-zero below
five distinct session dates.
"""
from __future__ import annotations

import json
import os
import subprocess
