def test_trend_consistency_hard_gate():
    """TC < 45 rejects; passing None disables the gate entirely."""
    # A saw-tooth that still climbs on VWAP/EMA but closes red most bars.
    bars = []
    px = 10.0
    for i in range(24):
        o = px + 0.30
        px = px + 0.05
        bars.append(_bar(px, o=o, h=max(o, px) + 0.05, l=min(o, px) - 0.05,
                         v=200_000, minute=5 * i))
    tc = ri.trend_consistency(bars)
    assert tc is not None and tc < 45, f"fixture should be choppy, got tc={tc}"
    gated = rs.evaluate_ticker("ABCD", bars, **_gate_kwargs())
    assert gated["passes"] is False and gated["counter"] == "conditions"
    ungated = rs.evaluate_ticker("ABCD", bars, min_trend_consistency=None,
                                 **_gate_kwargs())
    assert ungated["trend_consistency"] == tc


