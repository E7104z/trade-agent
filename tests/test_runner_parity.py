ET = timezone(timedelta(hours=-4))
FIXTURE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "fixtures", "runner_parity")


def _bar(c, o=None, h=None, l=None, v=1000, minute=0):
    o = c if o is None else o
    return {
        "t": datetime(2026, 9, 11, 9, 30, tzinfo=ET) + timedelta(minutes=minute),
        "o": o, "h": h if h is not None else max(o, c),
        "l": l if l is not None else min(o, c), "c": c, "v": v,
    }


def _ramp(n, start=10.0, step=0.10, v=1000):
    """n bars climbing by `step`, each closing green."""
    return [_bar(start + step * i, o=start + step * i - step / 2, v=v, minute=5 * i)
            for i in range(n)]


def _accel(n, start=10.0, v=200_000):
    """A ramp that ACCELERATES.

    A perfectly linear ramp is degenerate for the EMA-slope check: for a
    straight line, EMA_p converges to x_n - s*(p-1)/2, so the 9-EMA at the
    last bar and the EMA3 three bars back land on exactly the same number and
    the slope is 0 up to float noise (measured: -1.8e-15, which trips the
    `slope <= 0` guard). Real tape is never straight; curvature is what the
    condition is actually testing for.
    """
    closes, px, step = [], start, 0.04
    for _ in range(n):
        px += step
        step *= 1.06
        closes.append(px)
    return [_bar(c, o=c - 0.02, v=v, minute=5 * i) for i, c in enumerate(closes)]


