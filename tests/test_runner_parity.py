def _fixture_paths():
    if not os.path.isdir(FIXTURE_DIR):
        return []
    return sorted(os.path.join(FIXTURE_DIR, f)
                  for f in os.listdir(FIXTURE_DIR) if f.endswith(".json"))


@pytest.mark.parametrize("path", _fixture_paths() or [None],
                         ids=lambda p: os.path.basename(p) if p else "no-fixtures")
def test_fixture_parity_against_dto_javascript(path):
    """Python must reproduce DTO's real JS exactly over identical bar arrays."""
    if path is None:
        pytest.skip("no parity fixtures - run scripts/runner_parity_fixtures.py")
    import runpy
    import sys
    scripts = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "scripts")
    sys.path.insert(0, scripts)
    try:
        harness = runpy.run_path(os.path.join(scripts, "runner_parity.py"))
    finally:
        sys.path.remove(scripts)
    failures = harness["run_fixture"](path)
    assert not failures, "\n".join(failures)


def test_fixture_coverage_meets_spec_minimum():
    """Spec 0.6: at least 5 DISTINCT session dates."""
    paths = _fixture_paths()
    if not paths:
        pytest.skip("no parity fixtures - run scripts/runner_parity_fixtures.py")
    dates = set()
    for p in paths:
        with open(p, encoding="utf-8") as fh:
            dates.add(json.load(fh)["session_date"])
    assert len(dates) >= 5, f"only {len(dates)} distinct session dates: {sorted(dates)}"
