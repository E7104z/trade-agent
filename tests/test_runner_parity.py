@pytest.mark.parametrize("missing", ["float_m", "earnings_days_away"])
def test_null_gate_policy_dto_passes_but_reject_rejects(missing):
    """Spec R-4: a gate that cannot run has not passed.

    DTO's live scanner passes silently on a null float/earnings
    (`if (f !== null && ...)`). Parity mode must reproduce that; Phase 1 must
    not. Both behaviours are pinned so neither can drift into the other.
    """
    bars = _accel(24)
    kwargs = _gate_kwargs(**{missing: None})

    dto = rs.evaluate_ticker("ABCD", bars, null_gates="dto", **kwargs)
    assert dto["passes"] is True
    assert missing.replace("_m", "").replace("_days_away", "") in \
        " ".join(dto["unavailable"])

    strict = rs.evaluate_ticker("ABCD", bars, null_gates="reject", **kwargs)
    assert strict["passes"] is False
    assert "unavailable" in strict["reason"]


